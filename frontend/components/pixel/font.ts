export const GLYPH_H = 5;

/** Normalise text to what the font can draw. */
export const fontText = (text: string) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase();

/** Text as a Frame (1px between letters), drawn with palette letter `ink`. */
export function textFrame(text: string, ink = "k"): Frame {
  const chars = [...fontText(text)].map((c) => GLYPHS[c] ?? GLYPHS["?"]);
  return Array.from({ length: GLYPH_H }, (_, y) => chars.map((g) => g[y].split("#").join(ink)).join("."));
}
